"""
Cluster datasets, reference tracers and draw sets for the robust-settings sweep
==============================================================================

Two datasets (autolens_profiling#436, justified against
``autolens_workspace/scripts/cluster/``):

``simple`` (synthetic)
    ``dataset/cluster/simple``, gitignored, regenerated by this repo's cluster
    simulator (``scripts/misc/simulators/cluster.py``) through the shared
    ``auto_simulate_if_missing`` path. The simulator's imaging noise seed is
    pinned (``np.random.seed(1)``) and the point positions are deterministic
    solver output, so the regeneration is reproducible; every produced file's
    sha256 and the simulator's own sha256 are recorded. Truth model: 2 main
    dPIE + 10 scaling dPIE + NFW host at z 0.5, sources at z 1.0 / 2.0 (the
    constants below are the simulator's and the cluster cell's; a gate checks
    the model's prior-median tracer reproduces the simulator's ``tracer.json``
    deflections). The stored positions are themselves solver output: they are
    compared, never the truth.

    Draws: the truth + ``n`` seeded draws of the FULL prior of the cluster
    cell's fused model (``scripts/cluster/image_plane/likelihood_breakdown.py``
    step 5: Gaussian priors at 1 % (floor 0.01) on every main-lens centre / ra /
    rs / b0, the shared scaling ``b0_ref`` and the NFW centre). Source-plane
    coordinates: the truth centres for the truth draw; for a prior draw, each
    system's observed images back-traced through that draw's tracer and
    averaged (the cell's step-1 convention, what a solved fit's beta* is close
    to).

``a2744`` (real, Bergamini et al. 2023 inputs)
    The four CSVs of ``autolens_workspace/dataset/cluster/a2744`` (never FITS)
    are copied into the gitignored ``dataset/cluster/a2744`` by
    :func:`produce_a2744`, with each file's sha256, the workspace path and its
    git SHA in ``provenance.json``. Model: the workspace ``start_here.py``
    model (2 core dPIE with free sigma / r_cut, 188 scaling dPIE on one shared
    sigma_ref with the reference-anchored relation, an NFW host with free
    mass_at_200), solved with the production solver 120 x 120 @ 1.0",
    precision 0.001, magnification threshold 0.1.

    **A2744 reference tracer unavailable** (recorded 2026-10-17): the issue asks
    for the Lenstool best fit "mapped through ``scripts/cluster/lenstool/``",
    falling back to the workspace model's maximum-likelihood result. Neither
    exists. ``scripts/cluster/lenstool/`` reconstructs the Mahler et al. 2023
    ``best.par`` of SMACS J0723 only; no Bergamini et al. 2023 best-fit
    parameter file is in the workspace (``dataset/cluster/a2744/mass.csv``'s
    sigma 290 km/s and r_cut 20" are, by ``prep.py``'s own comment,
    "initialization placeholders"), and no ``output/cluster/a2744`` result of a
    ``start_here.py`` fit exists. Parameters are never invented, so
    :func:`a2744_reference` raises :class:`ReferenceUnavailable` unless a
    reference file is supplied (``--a2744-reference PATH``): a JSON
    ``{"source": "<what it is and where it came from>", "parameters":
    {"<model path>": value, ...}}`` covering every free parameter of the
    workspace model exactly (``--list-a2744-parameters`` prints the paths),
    e.g. a ``start_here.py`` max-likelihood instance or a transcription of a
    published best fit. The perturbation draws are then the reference + ``n``
    seeded draws with every free parameter scaled by ``1 + N(0, frac)``. The
    special value ``prior-median-smoke`` runs the code path on the model's prior
    medians, labelled "A2744-geometry synthetic model (prior medians; not a
    fitted cluster model)" in the JSON and in every row: every row of such a
    run is diagnostic, the JSON is not quotable, and it is never the production
    model -- the human decides whether it is useful.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np


def profiling_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "ruff.toml").exists():
            return parent
    raise RuntimeError("autolens_profiling root (ruff.toml) not found")


ROOT = profiling_root()


class ReferenceUnavailable(RuntimeError):
    """No reference tracer can be built from published / fitted values."""


A2744_SMOKE_LABEL = "A2744-geometry synthetic model (prior medians; not a fitted cluster model)"

A2744_REFERENCE_UNAVAILABLE = (
    "A2744 reference tracer unavailable: autolens_workspace/scripts/cluster/lenstool/ maps only "
    "the SMACS J0723 (Mahler+23) best.par; no Bergamini+23 best-fit parameters are in the "
    "workspace (dataset/cluster/a2744/mass.csv values are prep.py's initialization "
    "placeholders) and no start_here.py max-likelihood result exists; supply one with "
    "--a2744-reference PATH (see _datasets.py)"
)


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def git_head(path: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(path), "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError) as exc:
        return f"unavailable: {type(exc).__name__}"


def _digests(directory: Path, patterns=("*",)) -> dict[str, str]:
    files = sorted({p for pat in patterns for p in directory.glob(pat) if p.is_file()})
    return {p.name: sha256(p) for p in files}


@dataclass
class ClusterCase:
    """One dataset: model, sources, production solver, oracle box and draws."""

    name: str
    model: object
    source_names: list
    source_redshifts: list
    observed_positions: list
    position_sigma: float
    production: dict
    oracle_box: tuple
    oracle_h: float
    reference_vector: np.ndarray
    reference_label: str
    reference_available: bool
    provenance: dict
    fixed_galaxies: list = field(default_factory=list)
    truth_betas: np.ndarray | None = None
    draw_kind: str = "prior"
    perturbation_fraction: float | None = None

    # -- tracers -----------------------------------------------------------

    def galaxies_from_instance(self, instance) -> list:
        galaxies = list(instance.galaxies)
        if hasattr(instance, "scaling_galaxies"):
            galaxies += list(instance.scaling_galaxies)
        return galaxies + list(self.fixed_galaxies)

    def tracer_from_vector(self, vector, xp=np):
        import autolens as al

        instance = self.model.instance_from_vector(vector=vector, xp=xp)
        return al.Tracer(galaxies=self.galaxies_from_instance(instance))

    def plane_indices(self, tracer) -> list[int]:
        return [
            int(tracer.plane_index_via_redshift_from(redshift=z)) for z in self.source_redshifts
        ]

    # -- draws ----------------------------------------------------------------

    def draws(self, n: int, seed: int) -> np.ndarray:
        """Row 0 = the reference / truth vector, then ``n`` seeded draws."""
        rng = np.random.default_rng(seed)
        out = [np.asarray(self.reference_vector, dtype=float)]
        for _ in range(n):
            if self.draw_kind == "prior":
                unit = rng.uniform(1e-4, 1 - 1e-4, size=self.model.prior_count)
                out.append(np.asarray(self.model.vector_from_unit_vector(unit), dtype=float))
            else:
                frac = float(self.perturbation_fraction)
                out.append(
                    self.reference_vector
                    * (1.0 + frac * rng.standard_normal(self.model.prior_count))
                )
        return np.stack(out)

    def betas(self, vector, index: int) -> np.ndarray:
        """Source-plane coordinates (n_src, 2) for a draw (truth centres for draw 0 if known)."""
        if index == 0 and self.truth_betas is not None:
            return np.asarray(self.truth_betas, dtype=float)
        import autolens as al

        tracer = self.tracer_from_vector(vector)
        out = []
        for pos, idx in zip(self.observed_positions, self.plane_indices(tracer)):
            traced = np.asarray(tracer.traced_grid_2d_list_from(grid=al.Grid2DIrregular(pos))[idx])
            out.append(traced.mean(axis=0))
        return np.asarray(out, dtype=float)

    def observed_bbox(self) -> tuple:
        p = np.concatenate([np.atleast_2d(x) for x in self.observed_positions])
        return (
            float(p[:, 0].min()),
            float(p[:, 0].max()),
            float(p[:, 1].min()),
            float(p[:, 1].max()),
        )


