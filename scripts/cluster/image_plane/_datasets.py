SIMPLE_PATH = ROOT / "dataset" / "cluster" / "simple"
SIMPLE_REDSHIFT_LENS = 0.5
SIMPLE_MAIN = [((0.0, 0.0), 8.0, 20.0, 3.0), ((10.0, 8.0), 5.0, 12.0, 1.2)]  # centre, ra, rs, b0
SIMPLE_SCALING_B0_REF, SIMPLE_SCALING_RS_REF, SIMPLE_SCALING_RA, SIMPLE_EXPONENT = (
    0.12,
    10.0,
    0.1,
    0.5,
)
SIMPLE_NFW_MASS = 10**15.3
SIMPLE_TRUTH_SOURCE_CENTRES = [(0.3, 0.5), (-0.8, 1.2)]  # scripts/misc/simulators/cluster.py
SIMPLE_SIMULATOR_SEED = 1  # np.random.seed(1) in the simulator (imaging noise only)
# Production solver of autolens_workspace/scripts/cluster/modeling.py (the simple dataset's fit).
SIMPLE_PRODUCTION = {
    "shape_native": [100, 100],
    "pixel_scale": 1.0,
    "pixel_scale_precision": 0.001,
    "magnification_threshold": 0.1,
    "source": "autolens_workspace/scripts/cluster/modeling.py",
}


def produce_simple() -> dict:
    """Regenerate dataset/cluster/simple if missing (pinned seed); return its provenance."""
    from _profile_cli import auto_simulate_if_missing

    auto_simulate_if_missing(
        SIMPLE_PATH, dataset_type="cluster", instrument="simple", workspace_root=ROOT
    )
    simulator = ROOT / "scripts" / "misc" / "simulators" / "cluster.py"
    return {
        "path": "dataset/cluster/simple",
        "producer": "scripts/misc/simulators/cluster.py via _profile_cli.auto_simulate_if_missing",
        "simulator_sha256": sha256(simulator),
        "simulator_seed": SIMPLE_SIMULATOR_SEED,
        "positions_are_solver_output": True,
        "files_sha256": _digests(SIMPLE_PATH, ("*.csv", "*.json", "*.fits")),
    }


def _gaussian(mean, fraction=0.01, floor=0.01):
    import autofit as af

    return af.GaussianPrior(mean=float(mean), sigma=max(abs(float(mean)) * fraction, floor))


def simple_model(scaling_table, source_redshift_max):
    """The cluster cell's fused lens model (step 5), sources excluded (fixed galaxies)."""
    import autofit as af
    import autolens as al

    galaxies = {}
    for i, (centre, ra, rs, b0) in enumerate(SIMPLE_MAIN):
        mass = af.Model(al.mp.dPIEMassB0Sph)
        mass.centre.centre_0 = _gaussian(centre[0])
        mass.centre.centre_1 = _gaussian(centre[1])
        mass.ra = _gaussian(ra)
        mass.rs = _gaussian(rs)
        mass.b0 = _gaussian(b0)
        galaxies[f"main_{i}"] = af.Model(al.Galaxy, redshift=SIMPLE_REDSHIFT_LENS, mass=mass)
    b0_ref = _gaussian(SIMPLE_SCALING_B0_REF, floor=0.001)
    lum_ref = max(scaling_table.luminosities)
    for i, (centre, lum) in enumerate(zip(scaling_table.centres, scaling_table.luminosities)):
        ratio = (lum / lum_ref) ** SIMPLE_EXPONENT
        mass = af.Model(al.mp.dPIEMassB0Sph)
        mass.centre = tuple(centre)
        mass.ra = SIMPLE_SCALING_RA
        mass.rs = SIMPLE_SCALING_RS_REF * ratio
        mass.b0 = b0_ref * ratio
        galaxies[f"scaling_{i}"] = af.Model(al.Galaxy, redshift=SIMPLE_REDSHIFT_LENS, mass=mass)
    dark = af.Model(
        al.mp.NFWMCRLudlowSph,
        mass_at_200=SIMPLE_NFW_MASS,
        redshift_object=SIMPLE_REDSHIFT_LENS,
        redshift_source=source_redshift_max,
    )
    dark.centre.centre_0 = _gaussian(0.0)
    dark.centre.centre_1 = _gaussian(0.0)
    galaxies["host_halo"] = af.Model(al.Galaxy, redshift=SIMPLE_REDSHIFT_LENS, dark=dark)
    return af.Collection(galaxies=af.Collection(**galaxies))


def load_simple(
    oracle_h: float | None = None, oracle_half_width: float | None = None
) -> ClusterCase:
    import autolens as al

    provenance = produce_simple()
    datasets = al.list_from_csv(file_path=SIMPLE_PATH / "point_datasets.csv")
    scaling_table = al.galaxy_table_from_csv(file_path=SIMPLE_PATH / "scaling_galaxies.csv")
    redshifts = [float(d.redshift) for d in datasets]
    model = simple_model(scaling_table, max(redshifts))
    half = 60.0 if oracle_half_width is None else float(oracle_half_width)
    case = ClusterCase(
        name="simple",
        model=model,
        source_names=[d.name for d in datasets],
        source_redshifts=redshifts,
        observed_positions=[np.atleast_2d(np.asarray(d.positions, dtype=float)) for d in datasets],
        position_sigma=float(np.asarray(datasets[0].positions_noise_map).ravel()[0]),
        production=SIMPLE_PRODUCTION,
        oracle_box=(-half, half, -half, half),
        oracle_h=0.1 if oracle_h is None else float(oracle_h),
        reference_vector=np.asarray(model.physical_values_from_prior_medians, dtype=float),
        reference_label="simulator truth (prior medians of the cell's fused model)",
        reference_available=True,
        provenance=provenance,
        fixed_galaxies=[al.Galaxy(redshift=z) for z in redshifts],
        truth_betas=np.asarray(SIMPLE_TRUTH_SOURCE_CENTRES, dtype=float),
        draw_kind="prior",
    )
    case.provenance["truth_gate"] = simple_truth_gate(case)
    return case


def simple_truth_gate(case: ClusterCase) -> dict:
    """The model's truth tracer reproduces the simulator's tracer.json deflections."""
    import autolens as al

    path = SIMPLE_PATH / "tracer.json"
    if not path.exists():
        return {"pass": None, "reason": "tracer.json missing"}
    stored = al.from_json(file_path=path)
    ours = case.tracer_from_vector(case.reference_vector)
    rng = np.random.default_rng(0)
    pts = rng.uniform(-40, 40, size=(256, 2))
    worst = 0.0
    for z in case.source_redshifts:
        a = np.asarray(
            stored.traced_grid_2d_list_from(grid=al.Grid2DIrregular(pts))[
                stored.plane_index_via_redshift_from(redshift=z)
            ]
        )
        b = np.asarray(
            ours.traced_grid_2d_list_from(grid=al.Grid2DIrregular(pts))[
                ours.plane_index_via_redshift_from(redshift=z)
            ]
        )
        worst = max(worst, float(np.abs(a - b).max()))
    return {"max_abs_traced_difference_arcsec": worst, "pass": bool(worst < 1e-10)}


