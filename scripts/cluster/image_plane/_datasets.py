def _find_workspace() -> Path | None:
    for parent in Path(__file__).resolve().parents:
        cand = parent / "autolens_workspace"
        if (cand / "dataset" / "cluster" / "a2744" / "point_datasets.csv").exists():
            return cand
    return None


def produce_a2744(workspace: Path | None = None) -> dict:
    """Copy the A2744 CSVs (never FITS) into the gitignored dataset dir with sha256 provenance."""
    workspace = Path(workspace) if workspace is not None else _find_workspace()
    prov_path = A2744_PATH / "provenance.json"
    if workspace is None:
        if prov_path.exists():
            prov = json.loads(prov_path.read_text())
            for name, digest in prov["files_sha256"].items():
                if sha256(A2744_PATH / name) != digest:
                    raise RuntimeError(
                        f"dataset/cluster/a2744/{name} changed since it was produced"
                    )
            prov["reused"] = True
            return prov
        raise FileNotFoundError(
            "autolens_workspace not found beside autolens_profiling and dataset/cluster/a2744 "
            "not produced; pass --a2744-workspace PATH"
        )
    source = workspace / "dataset" / "cluster" / "a2744"
    A2744_PATH.mkdir(parents=True, exist_ok=True)
    for name in A2744_FILES:
        shutil.copyfile(source / name, A2744_PATH / name)
    prov = {
        "path": "dataset/cluster/a2744",
        "producer": "scripts/cluster/image_plane/_datasets.py::produce_a2744 (CSV copy, no FITS)",
        "source": "autolens_workspace/dataset/cluster/a2744 (Bergamini et al. 2023, VizieR J/A+A/670/A60)",
        "autolens_workspace_sha": git_head(workspace),
        "source_files_sha256": {n: sha256(source / n) for n in A2744_FILES},
        "files_sha256": {n: sha256(A2744_PATH / n) for n in A2744_FILES},
    }
    prov_path.write_text(json.dumps(prov, indent=2))
    prov["reused"] = False
    return prov


def a2744_model(dataset_list, scaling_table):
    """The workspace start_here.py model (N = 6), sources excluded (fixed galaxies)."""
    import autofit as af
    import autolens as al

    mass_table = al.galaxy_models_from_csv(file_path=A2744_PATH / "mass.csv", family="mass")
    galaxy_models = al.galaxy_af_models_from_csv_tables(mass_table)
    for name in ("lens_0", "lens_1"):
        galaxy_models[name].mass.sigma = af.UniformPrior(lower_limit=50.0, upper_limit=600.0)
        galaxy_models[name].mass.r_cut = af.UniformPrior(lower_limit=2.0, upper_limit=40.0)
        galaxy_models[name].mass.H0 = 67.66
        galaxy_models[name].mass.Om0 = 0.30966
    galaxy_models["host_halo"].dark.mass_at_200 = af.LogUniformPrior(
        lower_limit=10**14.5, upper_limit=10**16.0
    )
    sigma_ref = af.UniformPrior(lower_limit=0.0, upper_limit=300.0)
    alpha, gamma = 0.25, 0.2
    beta_cut = 1.0 + gamma - 2.0 * alpha
    z_max = max(float(d.redshift) for d in dataset_list)
    scaling = []
    for centre, luminosity in zip(scaling_table.centres, scaling_table.luminosities):
        ratio = luminosity / 1.0
        mass = af.Model(al.mp.dPIEMassSph)
        mass.centre = tuple(centre)
        mass.sigma = sigma_ref * ratio**alpha
        mass.r_core = 0.0
        mass.r_cut = 5.0 * ratio**beta_cut
        mass.redshift_object = A2744_REDSHIFT_LENS
        mass.redshift_source = z_max
        mass.H0 = 67.66
        mass.Om0 = 0.30966
        scaling.append(af.Model(al.Galaxy, redshift=A2744_REDSHIFT_LENS, mass=mass))
    return af.Collection(
        galaxies=af.Collection(**galaxy_models), scaling_galaxies=af.Collection(scaling)
    )


def a2744_reference(model, reference: str | None) -> tuple[np.ndarray, str, bool]:
    """(vector, label, is_reference). Raises ReferenceUnavailable without a reference file."""
    if reference is None:
        raise ReferenceUnavailable(A2744_REFERENCE_UNAVAILABLE)
    if reference == "prior-median-smoke":
        return (
            np.asarray(model.physical_values_from_prior_medians, dtype=float),
            A2744_SMOKE_LABEL,
            False,
        )
    data = json.loads(Path(reference).read_text())
    params = data["parameters"]
    paths = [".".join(p) for p in model.unique_prior_paths]
    missing = [p for p in paths if p not in params]
    extra = [p for p in params if p not in paths]
    if missing or extra:
        raise ReferenceUnavailable(
            f"--a2744-reference {reference}: missing {missing}, unexpected {extra}"
        )
    return (
        np.asarray([float(params[p]) for p in paths]),
        f"{data.get('source', 'unlabelled reference')} (file sha256 {sha256(Path(reference))})",
        True,
    )


def load_a2744(
    reference: str | None,
    *,
    workspace: Path | None = None,
    perturbation: float = 0.02,
    oracle_h: float | None = None,
    oracle_half_width: float | None = None,
) -> ClusterCase:
    import autolens as al

    provenance = produce_a2744(workspace)
    datasets = al.list_from_csv(file_path=A2744_PATH / "point_datasets.csv")
    scaling_table = al.galaxy_table_from_csv(file_path=A2744_PATH / "scaling_galaxies.csv")
    model = a2744_model(datasets, scaling_table)
    vector, label, is_reference = a2744_reference(model, reference)
    redshifts = [float(d.redshift) for d in datasets]
    half = 80.0 if oracle_half_width is None else float(oracle_half_width)
    return ClusterCase(
        name="a2744",
        model=model,
        source_names=[d.name for d in datasets],
        source_redshifts=redshifts,
        observed_positions=[np.atleast_2d(np.asarray(d.positions, dtype=float)) for d in datasets],
        position_sigma=float(np.asarray(datasets[0].positions_noise_map).ravel()[0]),
        production=A2744_PRODUCTION,
        oracle_box=(-half, half, -half, half),
        oracle_h=0.2 if oracle_h is None else float(oracle_h),
        reference_vector=vector,
        reference_label=label,
        reference_available=is_reference,
        provenance=provenance,
        fixed_galaxies=[al.Galaxy(redshift=z) for z in redshifts],
        truth_betas=None,
        draw_kind="perturbation",
        perturbation_fraction=float(perturbation),
    )


def list_a2744_parameters(workspace: Path | None = None) -> list[str]:
    import autolens as al

    produce_a2744(workspace)
    datasets = al.list_from_csv(file_path=A2744_PATH / "point_datasets.csv")
    scaling_table = al.galaxy_table_from_csv(file_path=A2744_PATH / "scaling_galaxies.csv")
    return [".".join(p) for p in a2744_model(datasets, scaling_table).unique_prior_paths]
