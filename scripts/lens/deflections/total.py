"""
Numpy CPU Profiling: Deflection Angles — Total Mass Profiles
============================================================

Times ``deflections_yx_2d_from`` for the four total (light + dark) mass profiles on the grids a real
imaging fit uses, with **no library change applied** — this cell is the *before*
measurement for the ``numpy-deflections-cpu`` epic (PyAutoArray#514, phase 1).

``Isothermal`` / ``PowerLaw`` and their spherical siblings are the
lens-modelling workhorses: almost every SLaM pipeline stage traces a grid
through one of them, so their per-call cost multiplies straight through a
nested-sampling run. The elliptical / spherical pairs are measured together
on purpose — they share the deflection math and differ only in the geometry
code path, so the gap between the two rows *is* the cost of that path.

Three timings per profile, all of them calls into the installed library:

1. ``Grid2D`` — ``dataset.grids.pixelization`` (sub-size 1), the ray-trace grid.
2. ``Grid2DIrregular`` — ``dataset.grids.lp.over_sampled``, the over-sampled
   light-profile grid.
3. ``Tracer`` — the same deflection through a two-plane
   ``traced_grid_2d_list_from``, so the wrapper cost is measured, not assumed.

Method, pin policy and the ``--repin`` contract all live in ``_driver.py``;
the fiducial parameters live in ``_profiles.py``. This file is deliberately
thin: a prologue, the pinned expectations, and one call.

Output
------
``results/lens/deflections/total_summary_<instrument>_v<version>.{json,png}``
"""

